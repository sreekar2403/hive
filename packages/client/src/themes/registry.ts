/** Expand a seed into the full palette. Deterministic; Ledger's `exact` fields win over derivations. */
export function expandPalette(
  seed: CompactSeed,
  mode: ResolvedMode,
): HivePalette {
  const isLight = mode === "light";
  const derived: Omit<HivePalette, "colorScheme"> = {
    bg: seed.bg,
    surface: seed.surface,
    surface2: seed.surface2,
    surface3: mixHex(seed.surface2, seed.border, 0.55),
    border: seed.border,
    borderStrong: mixHex(seed.border, seed.text, 0.28),
    text: seed.text,
    textMuted: seed.textMuted,
    textFaint: mixHex(seed.textMuted, seed.bg, 0.45),
    accent: seed.accent,
    accentHover: isLight ? darken(seed.accent, 0.14) : lighten(seed.accent, 0.1),
    accentFg: seed.accentFg,
    accentSoft: withAlpha(seed.accent, isLight ? 0.1 : 0.14),
    accentLine: withAlpha(seed.accent, isLight ? 0.32 : 0.38),
    success: seed.ok,
    successSoft: withAlpha(seed.ok, isLight ? 0.12 : 0.15),
    info: seed.info,
    infoSoft: withAlpha(seed.info, isLight ? 0.12 : 0.15),
    warn: seed.warn,
    warnSoft: withAlpha(seed.warn, isLight ? 0.13 : 0.15),
    danger: seed.danger,
    dangerSoft: withAlpha(seed.danger, isLight ? 0.11 : 0.15),
    shadow: isLight
      ? `0 1px 2px ${withAlpha(seed.text, 0.06)}, 0 4px 12px ${withAlpha(seed.text, 0.05)}`
      : "0 1px 2px rgb(0 0 0 / 0.4), 0 4px 14px rgb(0 0 0 / 0.3)",
    shadowLg: isLight
      ? `0 8px 32px ${withAlpha(seed.text, 0.14)}`
      : "0 10px 40px rgb(0 0 0 / 0.55)",
    agentOpencode: mixHex(seed.ok, isLight ? "#1f8f77" : "#35c9a6", 0.55),
    agentClaude: mixHex(seed.danger, isLight ? "#c2532a" : "#ff8a5c", 0.55),
    agentPi: mixHex(seed.info, isLight ? "#4f52c4" : "#8b8ef0", 0.55),
    agentHive: seed.accent,
  };
  return { ...derived, ...seed.exact, colorScheme: mode };
}

export function getPalette(id: ThemeId, mode: ResolvedMode): HivePalette {
  return expandPalette(SEEDS[id][mode], mode);
}

